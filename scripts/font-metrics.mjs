// Generates packages/shared/src/typography/font-metrics.generated.ts: per-glyph advance widths of the licensed
// (SIL OFL) Hebrew Google Fonts the typography system uses, so the layout engine measures text instead of guessing.
// Usage: node scripts/font-metrics.mjs   (network: fonts.googleapis.com / fonts.gstatic.com; nothing is stored but metrics)
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const FONTS = {
  Heebo: [400, 500, 700, 800, 900],
  Rubik: [400, 500, 700, 900],
  Assistant: [400, 600, 800],
  'Frank Ruhl Libre': [400, 500, 700, 900],
  'Secular One': [400],
  'Suez One': [400],
  Karantina: [400, 700],
  Bellefair: [400],
  'Noto Serif Hebrew': [400, 600, 800],
  'IBM Plex Sans Hebrew': [400, 500, 700],
  'Amatic SC': [700],
  'Varela Round': [400],
};

const CHARS = [];
for (let c = 0x20; c <= 0x7e; c++) CHARS.push(c);
for (let c = 0x5d0; c <= 0x5ea; c++) CHARS.push(c);
CHARS.push(0x5be, 0x5f3, 0x5f4, 0x20aa, 0x2013, 0x2014, 0x2019, 0x201c, 0x201d, 0xa0, 0x2022, 0xd7);

async function ttfUrl(family, weight) {
  const css = await (
    await fetch(`https://fonts.googleapis.com/css2?family=${family.replace(/ /g, '+')}:wght@${weight}`, {
      headers: { 'User-Agent': 'Mozilla/4.0' },
    })
  ).text();
  const urls = [...css.matchAll(/url\((https:[^)]+)\)/g)].map((m) => m[1]);
  if (!urls.length) throw new Error(`No font URL for ${family} ${weight}: ${css.slice(0, 200)}`);
  return urls;
}

function parse(buf) {
  const v = new DataView(buf);
  const numTables = v.getUint16(4);
  const tables = {};
  for (let i = 0; i < numTables; i++) {
    const o = 12 + i * 16;
    const tag = String.fromCharCode(v.getUint8(o), v.getUint8(o + 1), v.getUint8(o + 2), v.getUint8(o + 3));
    tables[tag] = v.getUint32(o + 8);
  }
  if (!tables.cmap || !tables.hmtx) throw new Error('Not a TrueType/OpenType font with cmap+hmtx');
  const upm = v.getUint16(tables.head + 18);
  const ascender = v.getInt16(tables.hhea + 4);
  const descender = v.getInt16(tables.hhea + 6);
  const numH = v.getUint16(tables.hhea + 34);
  const advance = (gid) => v.getUint16(tables.hmtx + 4 * Math.min(gid, numH - 1));
  // cmap: the Windows Unicode BMP subtable (format 4)
  const cm = tables.cmap;
  let sub;
  for (let i = 0; i < v.getUint16(cm + 2); i++) {
    const p = v.getUint16(cm + 4 + i * 8), e = v.getUint16(cm + 6 + i * 8), off = v.getUint32(cm + 8 + i * 8);
    if (p === 3 && (e === 1 || e === 10) && v.getUint16(cm + off) === 4) { sub = cm + off; break; }
    if (p === 0 && v.getUint16(cm + off) === 4) sub ??= cm + off;
  }
  if (!sub) throw new Error('No format-4 cmap');
  const segX2 = v.getUint16(sub + 6);
  const ends = sub + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
  const glyph = (code) => {
    for (let s = 0; s < segX2 / 2; s++) {
      const end = v.getUint16(ends + 2 * s);
      if (code > end) continue;
      const start = v.getUint16(starts + 2 * s);
      if (code < start) return 0;
      const delta = v.getInt16(deltas + 2 * s), ro = v.getUint16(ranges + 2 * s);
      if (!ro) return (code + delta) & 0xffff;
      const g = v.getUint16(ranges + 2 * s + ro + 2 * (code - start));
      return g ? (g + delta) & 0xffff : 0;
    }
    return 0;
  };
  const adv = {};
  for (const c of CHARS) {
    const g = glyph(c);
    if (g) adv[String.fromCodePoint(c)] = Math.round((advance(g) / upm) * 1000) / 1000;
  }
  return { ascender: Math.round((ascender / upm) * 1000) / 1000, descender: Math.round((descender / upm) * 1000) / 1000, adv };
}

const out = {};
for (const [family, weights] of Object.entries(FONTS)) {
  out[family] = {};
  for (const w of weights) {
    // Google may split a family into subset files (hebrew, latin); merge their glyphs.
    const merged = { ascender: 0, descender: 0, adv: {} };
    for (const url of await ttfUrl(family, w)) {
      const m = parse(await (await fetch(url)).arrayBuffer());
      merged.ascender ||= m.ascender;
      merged.descender ||= m.descender;
      Object.assign(merged.adv, m.adv);
    }
    const missing = ['א', 'ש', '0', 'A'].filter((c) => !merged.adv[c]);
    if (missing.length) throw new Error(`${family} ${w} lacks ${missing.join(' ')}`);
    out[family][w] = merged;
    console.log(family, w, Object.keys(merged.adv).length, 'glyphs');
  }
}

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(here, '../packages/shared/src/typography/font-metrics.generated.ts');
writeFileSync(
  target,
  `// Generated by scripts/font-metrics.mjs from the fonts' own hmtx tables (Google Fonts, SIL Open Font License).\n` +
    `// Advance widths in em. Do not edit by hand.\n` +
    `export const FONT_METRICS: Record<string, Record<number, { ascender: number; descender: number; adv: Record<string, number> }>> = ${JSON.stringify(out)};\n`,
);
console.log('wrote', target);
